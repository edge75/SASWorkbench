#!/usr/bin/env python3
"""Generates the SAS protocol catalogue from the gaming machine library's own headers.

The catalogue is not hand-written. Long poll codes, exception codes and meter codes all
come from the enumerations the library itself dispatches on, so the two cannot drift: if a
long poll is added to the library, regenerating picks it up, and if one is renamed the
change shows up as a diff rather than as a test that mysteriously stops matching.

The library is the only source used. Third-party specification text is deliberately not
consulted or reproduced here.

Run it, then commit what it produces:

    python tools/protogen/protogen.py --libsas C:/Progetti/libsas
    python tools/protogen/protogen.py --check      # fails if the committed output is stale

Output:
    src/SasWorkbench.Core/Protocol/Generated/SasLongPollCode.g.cs
    src/SasWorkbench.Core/Protocol/Generated/SasExceptionCode.g.cs
    src/SasWorkbench.Core/Protocol/Generated/SasMeterCode.g.cs
    src/SasWorkbench.Core/Protocol/Generated/Catalogue.g.cs
"""

from __future__ import annotations

import argparse
import io
import re
import sys
from dataclasses import dataclass
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT_DIR = REPO / "src" / "SasWorkbench.Core" / "Protocol" / "Generated"

HEADER = """// <auto-generated>
//     Generated by tools/protogen/protogen.py from the gaming machine library's headers.
//     Do not edit by hand: run the generator and commit the result.
//     Source: {sources}
// </auto-generated>

#nullable enable
{usings}
namespace SasWorkbench.Core.Protocol;
"""


@dataclass(frozen=True)
class Entry:
    name: str
    value: int
    summary: str | None


def read(path: Path) -> str:
    return io.open(path, encoding="utf-8", errors="replace").read()


def enum_body(source: str, enum_name: str) -> str:
    match = re.search(r"enum\s+" + enum_name + r"\s*\{(.*?)\n\};", source, re.S)
    if not match:
        raise SystemExit(f"enum {enum_name} not found")
    return match.group(1)


def parse_enum(source: str, enum_name: str) -> list[Entry]:
    """Reads an enumeration, keeping each entry's doc comment where the header has one."""
    entries: list[Entry] = []
    pending: list[str] = []
    in_summary = False

    for line in enum_body(source, enum_name).splitlines():
        stripped = line.strip()

        if stripped.startswith("/// <summary>"):
            in_summary = True
            pending = []
            continue
        if stripped.startswith("/// </summary>"):
            in_summary = False
            continue
        if in_summary and stripped.startswith("///"):
            pending.append(stripped[3:].strip())
            continue

        member = re.match(r"([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(0[xX][0-9A-Fa-f]+|\d+)", stripped)
        if member:
            summary = " ".join(p for p in pending if p) or None
            entries.append(Entry(member.group(1), int(member.group(2), 0), summary))
            pending = []
            continue

        if stripped and not stripped.startswith("//"):
            pending = []

    return entries


def parse_long_poll_handlers(lp_header: str) -> dict[int, str]:
    """Maps each long poll code to the library's own handler name.

    The long poll enumeration carries no doc comments, but every handler is named for what
    it does — lp1F_SendGamingMachineIdAndInformation and so on — which is a better
    description than anything invented here, and it is first-party.
    """
    handlers: dict[int, str] = {}
    for match in re.finditer(r"\b(?:c?lp)([0-9A-Fa-f]{2})_([A-Za-z0-9_]+)\s*\(", lp_header):
        code = int(match.group(1), 16)
        handlers.setdefault(code, match.group(2))
    return handlers


def spaced(identifier: str) -> str:
    """Turns SendGamingMachineIdAndInformation into 'Send gaming machine id and information'."""
    words = re.sub(r"(?<!^)(?=[A-Z])", " ", identifier).replace("_", " ").split()
    if not words:
        return identifier
    return " ".join([words[0].capitalize()] + [w.lower() for w in words[1:]])


def escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"')


def xml_escape(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def unique_names(entries: list[Entry]) -> list[Entry]:
    """Drops later duplicates of the same value, keeping the first spelling."""
    seen: set[int] = set()
    kept: list[Entry] = []
    for entry in entries:
        if entry.value in seen:
            continue
        seen.add(entry.value)
        kept.append(entry)
    return kept


def header(sources: str, usings: str = "") -> str:
    return HEADER.format(sources=sources, usings=usings)


def emit_enum(
    csharp_name: str,
    underlying: str,
    entries: list[Entry],
    sources: str,
    doc: str,
) -> str:
    lines = [header(sources), f"/// <summary>{doc}</summary>",
             f"public enum {csharp_name} : {underlying}", "{"]
    for entry in entries:
        if entry.summary:
            lines.append(f"    /// <summary>{xml_escape(entry.summary)}</summary>")
        lines.append(f"    {entry.name} = 0x{entry.value:02X},")
        lines.append("")
    if lines[-1] == "":
        lines.pop()
    lines.append("}")
    return "\n".join(lines) + "\n"


def emit_catalogue(
    long_polls: list[Entry],
    handlers: dict[int, str],
    exceptions: list[Entry],
    meters: list[Entry],
    sources: str,
) -> str:
    lines = [header(sources, "\nusing System.Collections.Frozen;\n"),
             "/// <summary>",
             "/// Every long poll, exception and meter the gaming machine library knows about,",
             "/// with the name it uses for each.",
             "/// </summary>",
             "public static class SasCatalogue", "{"]

    lines.append("    /// <summary>Long poll commands, by code.</summary>")
    lines.append("    public static FrozenDictionary<byte, SasLongPollInfo> LongPolls { get; } =")
    lines.append("        new Dictionary<byte, SasLongPollInfo>")
    lines.append("        {")
    for entry in long_polls:
        handler = handlers.get(entry.value)
        description = spaced(handler) if handler else spaced(entry.name.removeprefix("LP_").title())
        lines.append(
            f'            [0x{entry.value:02X}] = new(0x{entry.value:02X}, "{entry.name}", '
            f'"{escape(description)}"),')
    lines.append("        }.ToFrozenDictionary();")
    lines.append("")

    lines.append("    /// <summary>Exception codes, by code.</summary>")
    lines.append("    public static FrozenDictionary<byte, SasExceptionInfo> Exceptions { get; } =")
    lines.append("        new Dictionary<byte, SasExceptionInfo>")
    lines.append("        {")
    for entry in exceptions:
        description = entry.summary or spaced(entry.name)
        lines.append(
            f'            [0x{entry.value:02X}] = new(0x{entry.value:02X}, "{entry.name}", '
            f'"{escape(description)}"),')
    lines.append("        }.ToFrozenDictionary();")
    lines.append("")

    lines.append("    /// <summary>Meter codes, by code.</summary>")
    lines.append("    public static FrozenDictionary<ushort, SasMeterInfo> Meters { get; } =")
    lines.append("        new Dictionary<ushort, SasMeterInfo>")
    lines.append("        {")
    for entry in meters:
        description = entry.summary or spaced(entry.name)
        lines.append(
            f'            [0x{entry.value:04X}] = new(0x{entry.value:04X}, "{entry.name}", '
            f'"{escape(description)}"),')
    lines.append("        }.ToFrozenDictionary();")
    lines.append("")
    lines.append("    /// <summary>How many of each the catalogue holds, for a report header.</summary>")
    lines.append("    public static (int LongPolls, int Exceptions, int Meters) Counts =>")
    lines.append("        (LongPolls.Count, Exceptions.Count, Meters.Count);")
    lines.append("}")
    return "\n".join(lines) + "\n"


def emit_info_types(sources: str) -> str:
    return header(sources) + """
/// <summary>One long poll command, as the gaming machine library names it.</summary>
/// <param name="Code">The command byte.</param>
/// <param name="Symbol">The library's own identifier for it.</param>
/// <param name="Description">What it does, taken from the library's handler name.</param>
public sealed record SasLongPollInfo(byte Code, string Symbol, string Description)
{
    public override string ToString() => $"${Code:X2} {Description}";
}

/// <summary>One exception code.</summary>
/// <param name="Code">The code a general poll returns.</param>
/// <param name="Symbol">The library's own identifier for it.</param>
/// <param name="Description">What it means, from the library's own documentation.</param>
public sealed record SasExceptionInfo(byte Code, string Symbol, string Description)
{
    public override string ToString() => $"${Code:X2} {Description}";
}

/// <summary>One meter.</summary>
/// <param name="Code">The meter code.</param>
/// <param name="Symbol">The library's own identifier for it.</param>
/// <param name="Description">What it counts, from the library's own documentation.</param>
public sealed record SasMeterInfo(ushort Code, string Symbol, string Description)
{
    public override string ToString() => $"${Code:X4} {Description}";
}
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--libsas", default=r"C:\Progetti\libsas",
                        help="root of the gaming machine library checkout")
    parser.add_argument("--check", action="store_true",
                        help="do not write; exit non-zero if the committed output is stale")
    args = parser.parse_args()

    root = Path(args.libsas)
    libsas_h = root / "include" / "libsas.h"
    lp_h = root / "include" / "lp.h"
    if not libsas_h.exists() or not lp_h.exists():
        print(f"headers not found under {root}", file=sys.stderr)
        return 2

    source = read(libsas_h)
    sources = "include/libsas.h, include/lp.h"

    long_polls = unique_names(parse_enum(source, "SasLongPollCode"))
    exceptions = unique_names(parse_enum(source, "SasExceptionCode"))
    meters = unique_names(parse_enum(source, "SasMeterCode"))
    handlers = parse_long_poll_handlers(read(lp_h))

    files = {
        "SasLongPollCode.g.cs": emit_enum(
            "SasLongPollCode", "byte", long_polls, sources,
            "Every long poll command the gaming machine library dispatches."),
        "SasExceptionCode.g.cs": emit_enum(
            "SasExceptionCode", "byte", exceptions, sources,
            "Every exception a gaming machine can report in answer to a general poll."),
        "SasMeterCode.g.cs": emit_enum(
            "SasMeterCode", "ushort", meters, sources,
            "Every meter the gaming machine library can report."),
        "CatalogueInfo.g.cs": emit_info_types(sources),
        "Catalogue.g.cs": emit_catalogue(long_polls, handlers, exceptions, meters, sources),
    }

    stale = []
    for name, text in files.items():
        target = OUT_DIR / name
        current = read(target) if target.exists() else None
        if current == text:
            continue
        stale.append(name)
        if not args.check:
            target.parent.mkdir(parents=True, exist_ok=True)
            io.open(target, "w", encoding="utf-8", newline="\n").write(text)

    if args.check:
        if stale:
            print("stale generated files: " + ", ".join(sorted(stale)), file=sys.stderr)
            return 1
        print("generated catalogue is up to date")
        return 0

    print(f"{len(long_polls)} long polls, {len(exceptions)} exceptions, {len(meters)} meters "
          f"-> {OUT_DIR.relative_to(REPO)}")
    if stale:
        print("updated: " + ", ".join(sorted(stale)))
    else:
        print("no changes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
