#!/usr/bin/env python3
"""Generates the SAS protocol catalogue from the gaming machine library's own headers.

The catalogue is not hand-written. Long poll codes, exception codes and meter codes all
come from the enumerations the library itself dispatches on, so the two cannot drift: if a
long poll is added to the library, regenerating picks it up, and if one is renamed the
change shows up as a diff rather than as a test that mysteriously stops matching.

The library is the only source used. Third-party specification text is deliberately not
consulted or reproduced here.

Run it, then commit what it produces:

    python tools/protogen/protogen.py --libsas C:/Progetti/libsas
    python tools/protogen/protogen.py --check      # fails if the committed output is stale

Output:
    src/SasWorkbench.Core/Protocol/Generated/SasLongPollCode.g.cs
    src/SasWorkbench.Core/Protocol/Generated/SasExceptionCode.g.cs
    src/SasWorkbench.Core/Protocol/Generated/SasMeterCode.g.cs
    src/SasWorkbench.Core/Protocol/Generated/Catalogue.g.cs
"""

from __future__ import annotations

import argparse
import io
import re
import sys
from dataclasses import dataclass
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT_DIR = REPO / "src" / "SasWorkbench.Core" / "Protocol" / "Generated"

HEADER = """// <auto-generated>
//     Generated by tools/protogen/protogen.py from the gaming machine library's headers.
//     Do not edit by hand: run the generator and commit the result.
//     Source: {sources}
// </auto-generated>

#nullable enable
{usings}
namespace SasWorkbench.Core.Protocol;
"""


BLOCK_COMMENT = r"/\*.*?\*/"
LINE_COMMENT = r"//[^\n]*"
NOT_NEWLINE = r"[^\n]"


@dataclass(frozen=True)
class Entry:
    name: str
    value: int
    summary: str | None


def read(path: Path) -> str:
    return io.open(path, encoding="utf-8", errors="replace").read()


def enum_body(source: str, enum_name: str) -> str:
    """Reads one enumeration's members, however the header spells the declaration.

    Both forms appear in the same header: a plain `enum Name { ... };`, and a
    `typedef enum _Name { ... } Name;` whose closing brace is followed by a name.
    """
    match = re.search(r"enum\s+" + enum_name + r"\s*\{(.*?)\n\}\s*[A-Za-z0-9_]*\s*;", source, re.S)
    if not match:
        raise SystemExit(f"enum {enum_name} not found")
    return match.group(1)


def parse_enum(source: str, enum_name: str) -> list[Entry]:
    """Reads an enumeration, keeping each entry's doc comment where the header has one."""
    entries: list[Entry] = []
    pending: list[str] = []
    in_summary = False

    for line in enum_body(source, enum_name).splitlines():
        stripped = line.strip()

        if stripped.startswith("/// <summary>"):
            in_summary = True
            pending = []
            continue
        if stripped.startswith("/// </summary>"):
            in_summary = False
            continue
        if in_summary and stripped.startswith("///"):
            pending.append(stripped[3:].strip())
            continue

        member = re.match(r"([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(0[xX][0-9A-Fa-f]+|\d+)", stripped)
        if member:
            summary = " ".join(p for p in pending if p) or None
            entries.append(Entry(member.group(1), int(member.group(2), 0), summary))
            pending = []
            continue

        if stripped and not stripped.startswith("//"):
            pending = []

    return entries


def parse_long_poll_handlers(lp_header: str) -> dict[int, str]:
    """Maps each long poll code to the library's own handler name.

    The long poll enumeration carries no doc comments, but every handler is named for what
    it does — lp1F_SendGamingMachineIdAndInformation and so on — which is a better
    description than anything invented here, and it is first-party.
    """
    handlers: dict[int, str] = {}
    for match in re.finditer(r"\b(?:c?lp)([0-9A-Fa-f]{2})_([A-Za-z0-9_]+)\s*\(", lp_header):
        code = int(match.group(1), 16)
        handlers.setdefault(code, match.group(2))
    return handlers


def parse_dispatch(threads_source: str, long_polls: list[Entry]) -> dict[int, str]:
    """Maps each long poll code to the handler the library actually dispatches it to.

    Read from the dispatcher rather than from the header's declarations, because the two do not
    agree and the dispatcher is the one that decides. Nine commands share one handler whose name
    carries no code at all, so a map built from names alone reports those as unhandled — and a
    command reported as unhandled is one this project would go on to call unestablishable.

    A case label with no call before its break belongs to a command the dispatcher lists and
    answers inline, and is left out, so that "dispatched to a handler" means exactly that.
    """
    by_symbol = {entry.name: entry.value for entry in long_polls}
    dispatch: dict[int, str] = {}
    pending: list[str] = []
    unmatched: set[str] = set()

    for line in strip_comments(threads_source).splitlines():
        label = re.search(r"\bcase\s+(LP_[A-Za-z0-9_]+)\s*:", line)
        if label:
            pending.append(label.group(1))
            continue

        call = re.search(r"\b(c?lp[0-9A-Fa-fX]{2}_[A-Za-z0-9_]+)\s*\(", line)
        if call and pending:
            for symbol in pending:
                if symbol in by_symbol:
                    dispatch.setdefault(by_symbol[symbol], call.group(1))
                else:
                    unmatched.add(symbol)
            pending = []
            continue

        if "break;" in line:
            pending = []

    # A label whose symbol is not in the enumeration means the two have drifted apart. Dropped in
    # silence it would be indistinguishable from a command the dispatcher genuinely does not
    # handle, which is a fact this catalogue then states.
    if unmatched:
        print("dispatcher labels with no entry in the enumeration: "
              + ", ".join(sorted(unmatched)), file=sys.stderr)

    return dispatch


def parse_function_bodies(source: str) -> dict[str, str]:
    """Reads every top-level function in a source file, by name.

    The library's own style puts the opening brace of a function definition alone in column
    zero and indents everything inside it, which is what makes this possible without a C
    parser. Anything that does not match that shape is not read as a function at all, rather
    than half-read.
    """
    text = strip_comments(source)
    lines = text.split("\n")
    offsets: list[int] = []
    position = 0
    for line in lines:
        offsets.append(position)
        position += len(line) + 1

    bodies: dict[str, str] = {}
    for index, line in enumerate(lines):
        if not line.startswith("{") or index == 0:
            continue

        signature: list[str] = []
        back = index - 1
        while back >= 0 and lines[back].strip() and len(signature) < 8:
            signature.insert(0, lines[back])
            back -= 1

        named = re.search(r"\b([A-Za-z_][A-Za-z0-9_]*)\s*\([^()]*\)\s*$", " ".join(signature).strip())
        if not named:
            continue

        start = offsets[index]
        depth = 0
        cursor = start
        while cursor < len(text):
            if text[cursor] == "{":
                depth += 1
            elif text[cursor] == "}":
                depth -= 1
                if depth == 0:
                    break
            cursor += 1
        bodies[named.group(1)] = text[start:cursor + 1]

    return bodies


HANDLER_NAME = r"^(?:c?lp[0-9A-Fa-fX]{2}_)"
CRC_CHECK = r"[{}]|crcCheck\s*\("


def check_sequence_requirement(bodies: dict[str, str], handler: str,
                               seen: set[str] | None = None) -> str:
    """Says whether the library's handler refuses a host message with no check sequence.

    The library checks a received message in two places and only one of them is a rule about
    the command. Its receive thread checks the sequence on any message longer than two bytes;
    a handler that calls crcCheck itself checks it again, and on a two-byte message that call
    reads the address and the command byte *as* the sequence and can never pass. So a command
    whose handler calls crcCheck refuses a bare two-byte poll, and one whose handler does not
    answers it.

    Returned as three values rather than two. 'always' and 'never' are facts about the
    handler; 'conditional' is a handler that checks only down some branch, which is a thing
    this reader cannot settle and must not average out. Nesting is how the three are told
    apart: a call at statement level of the function runs on every path through it.
    """
    if seen is None:
        seen = set()
    if handler in seen or handler not in bodies:
        return "unknown"
    seen.add(handler)

    body = bodies[handler]
    depth = 0
    depths: list[int] = []
    for token in re.finditer(CRC_CHECK, body):
        text = token.group(0)
        if text == "{":
            depth += 1
        elif text == "}":
            depth -= 1
        else:
            depths.append(depth)

    if depths:
        return "always" if min(depths) == 1 else "conditional"

    # Eleven commands answer through a shared helper and check nothing themselves, so a reader
    # that stopped at the dispatched handler would report every bill-count poll as checking
    # when its helper does not, or the reverse.
    for callee in sorted(set(re.findall(r"\b([A-Za-z_][A-Za-z0-9_]*)\s*\(", body))):
        if callee != handler and re.match(HANDLER_NAME, callee):
            answer = check_sequence_requirement(bodies, callee, seen)
            if answer != "never":
                return answer

    return "never"


# The multi-denomination preamble carries another command inside it, so the meters it reports are
# whichever command it was given rather than a property of $B0. Read like any other handler it
# reports the first base command its switch happens to name, which would be a fact about the
# switch's order and nothing else.
CARRIES_ANOTHER_COMMAND = {0xB0}

METER_CODE_ARRAY = re.compile(r"meterCodes\s*\[\s*\]\s*=\s*\{([^}]*)\}", re.S)
SHARED_METER_CALL = re.compile(r"\blpXX_SendMeter\s*\(([^;]*?)\)\s*;", re.S)
DIRECT_METER_CALL = re.compile(r"\binternalReadMeter\s*\(([^;]*?)\)\s*;", re.S)


def _arguments(text: str) -> list[str]:
    """Splits a call's arguments on the commas that are not inside brackets."""
    parts: list[str] = []
    depth = 0
    current = ""
    for character in text:
        if character in "([":
            depth += 1
        elif character in ")]":
            depth -= 1
        if character == "," and depth == 0:
            parts.append(current.strip())
            current = ""
        else:
            current += character
    if current.strip():
        parts.append(current.strip())
    return parts


def meters_read_by(bodies: dict[str, str], handler: str, meter_names: set[str],
                   seen: set[str] | None = None) -> tuple[list[str], bool]:
    """Which meters one handler reports, in the order it writes them, and how it reads them.

    Two ways of reading a meter live in this library and they do not answer the same number.
    The shared single-meter helper divides the value by the accounting denomination for a meter
    that is not one of the multigame ones, under two of the machine's meter modes; every other
    handler reads the meter and writes it as it stands. So which helper a command goes through is
    a property of the command, and it decides which of two commands reporting one meter a test
    should be reading it from.

    Read the same way the check-sequence rule is: from the dispatched handler, following one
    named helper where the handler is only a call to one.
    """
    if seen is None:
        seen = set()
    if handler in seen or handler not in bodies:
        return ([], False)
    seen.add(handler)

    body = bodies[handler]
    found: list[str] = []
    shared = False

    for call in SHARED_METER_CALL.finditer(body):
        arguments = _arguments(call.group(1))
        if len(arguments) >= 3 and arguments[2] in meter_names:
            found.append(arguments[2])
            shared = True

    for array in METER_CODE_ARRAY.finditer(body):
        items = [item.strip() for item in array.group(1).split(",") if item.strip()]
        if items and all(item in meter_names for item in items):
            found.extend(items)

    for call in DIRECT_METER_CALL.finditer(body):
        arguments = _arguments(call.group(1))
        if len(arguments) >= 3 and arguments[2] in meter_names and arguments[2] not in found:
            found.append(arguments[2])

    if found:
        return (found, shared)

    for callee in sorted(set(re.findall(r"\b([A-Za-z_][A-Za-z0-9_]*)\s*\(", body))):
        if callee != handler and re.match(HANDLER_NAME, callee):
            meters, through_shared = meters_read_by(bodies, callee, meter_names, seen)
            if meters:
                return (meters, through_shared)

    return ([], False)


def parse_meter_reads(lp_source: str, dispatch: dict[int, str],
                      meters: list[Entry]) -> dict[int, tuple[list[int], bool]]:
    """Maps each dispatched long poll to the meters it reports and how it reads them."""
    bodies = parse_function_bodies(lp_source)
    by_name = {entry.name: entry.value for entry in meters}
    reads: dict[int, tuple[list[int], bool]] = {}

    for code, handler in sorted(dispatch.items()):
        if code in CARRIES_ANOTHER_COMMAND:
            continue
        found, shared = meters_read_by(bodies, handler, set(by_name))
        if found:
            reads[code] = ([by_name[name] for name in found], shared)

    return reads


def parse_multigame_meters(utils_source: str, meters: list[Entry]) -> list[int]:
    """The meters the library calls multigame, read from the predicate that decides it.

    It matters here for one reason: the shared single-meter helper divides every meter that is
    *not* in this set by the accounting denomination. So the set is half of the rule that says
    whether two commands reporting one meter can disagree, and copying it by hand would be the
    half that goes stale.
    """
    bodies = parse_function_bodies(utils_source)
    body = bodies.get("isMultigameMeter")
    if body is None:
        raise SystemExit("isMultigameMeter not found")

    by_name = {entry.name: entry.value for entry in meters}
    found: list[int] = []
    for name in re.findall(r"meter\s*==\s*([A-Za-z_][A-Za-z0-9_]*)", body):
        if name in by_name and by_name[name] not in found:
            found.append(by_name[name])

    if not found:
        raise SystemExit("isMultigameMeter named no meter this catalogue knows")

    return found


def parse_check_sequences(lp_source: str, dispatch: dict[int, str]) -> dict[int, bool]:
    """Maps each dispatched long poll to whether the host must end its message in a check
    sequence, read from the handler the dispatcher sends it to."""
    bodies = parse_function_bodies(lp_source)
    required: dict[int, bool] = {}
    undecided: list[str] = []

    for code, handler in sorted(dispatch.items()):
        answer = check_sequence_requirement(bodies, handler)
        if answer == "always":
            required[code] = True
        elif answer == "never":
            required[code] = False
        else:
            undecided.append(f"${code:02X} {handler} ({answer})")

    # A handler this reader cannot settle is left out of the map and named, because a command
    # recorded as not needing a check sequence is one this host would then frame without one.
    if undecided:
        print("check sequence undecided for: " + ", ".join(undecided), file=sys.stderr)

    return required


# The receiver's table spells a variable-length command as -1, which is the value that sends it
# down the read-a-length-byte path rather than the read-this-many-bytes one.
VARIABLE_LENGTH = -1


def parse_channel_categories(wrapper_header: str) -> list[str]:
    """The categories a channel can own, read from the library's own channel-control bitfield.

    SAS 6.02 treats every channel as an independent entity, and the library states which
    independences there are exactly once: as the one-bit fields of sChannelControl. Read from
    there rather than listed here, so a category added to the library arrives as a diff.
    """
    body = re.search(r"typedef\s+struct\s+_sChannelControl\s*\{(.*?)\}\s*sChannelControl\s*;",
                     strip_comments(wrapper_header), re.S)
    if not body:
        raise SystemExit("the library's channel control structure was not found")

    names = [name for name, width in
             re.findall(r"unsigned\s+int\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*(\d+)", body.group(1))
             if width == "1"]
    if not names:
        raise SystemExit("the library's channel control structure named no categories")

    return names


def enclosing_condition(body: str, at: int) -> str | None:
    """The `if (...)` a gate sits inside, when it sits inside one rather than at the top."""
    opened = body.rfind("{", 0, at)
    while opened >= 0:
        head = body[:opened].rstrip()
        condition = re.search(r"if\s*\(((?:[^()]|\([^()]*\))*)\)$", head)
        if condition:
            return condition.group(1)
        opened = body.rfind("{", 0, opened)
    return None


def category_gate(bodies: dict[str, str], handler: str) -> tuple[str, list[str]] | None:
    """Which category one handler is gated on, and which commands its gate exempts.

    The library gates a long poll on the answering channel owning the command's category by
    returning without sending anything - "Otherwise ignore the LP" in its own words - so what a
    host on the wrong channel gets is silence and not a refusal. The two are not interchangeable:
    a refusal says the command was understood and declined.

    One handler serves nine commands and gates all but two of them, naming those two in the
    condition around its gate. They are read out of the condition rather than assumed, so a
    command the library exempts is exempted here.
    """
    body = bodies.get(handler)
    if body is None:
        return None

    found = list(re.finditer(r"!channelControl\.([A-Za-z_][A-Za-z0-9_]*)", body))
    if not found:
        return None

    categories = {match.group(1) for match in found}
    if len(categories) > 1:
        print(f"{handler} is gated on more than one category: " + ", ".join(sorted(categories)),
              file=sys.stderr)
        return None

    exempt: list[str] = []
    for match in found:
        condition = enclosing_condition(body, match.start())
        if condition:
            exempt.extend(re.findall(r"\b(LP_[A-Z0-9_]+)\b", condition))

    return categories.pop(), sorted(set(exempt))


def parse_command_categories(
        lp_source: str, dispatch: dict[int, str], long_polls: list[Entry]) -> dict[int, str]:
    """Maps each long poll to the channel category that owns it, where the library gates one.

    A command in no category is answered on any channel. That is not a hole to be filled in: the
    cashout ticket information poll is one of them, so a host on a channel that does not own
    validation is answered with the ticket's real validation number, which is a fact about the
    library worth stating.
    """
    bodies = parse_function_bodies(lp_source)
    by_code = {entry.value: entry.name for entry in long_polls}
    categories: dict[int, str] = {}

    for code, handler in sorted(dispatch.items()):
        gate = category_gate(bodies, handler)
        if gate is None:
            continue

        category, exempt = gate
        if by_code.get(code) in exempt:
            continue

        categories[code] = category

    return categories


def parse_exception_categories(utils_source: str, exceptions: list[Entry]) -> dict[int, str]:
    """Maps each exception to the channel category that owns it, from the library's predicates.

    The library keeps one exception buffer per channel and skips a channel that does not own the
    exception's category, so which host hears an exception is decided by these five functions and
    by nothing else. An exception none of them claims reaches every open channel - which is what
    makes a printed cashout ticket visible to a host that cannot then read the ticket.
    """
    bodies = parse_function_bodies(utils_source)
    by_symbol = {entry.name: entry.value for entry in exceptions}
    categories: dict[int, str] = {}
    unmatched: set[str] = set()

    for predicate, category in (
            ("isAftException", "aft"),
            ("isProgressiveException", "progressive"),
            ("isLegacyBonusException", "legacyBonus"),
            ("isValidationException", "validation"),
            ("isComponentAuthenticationException", "componentAuthentication")):
        body = bodies.get(predicate)
        if body is None:
            raise SystemExit(f"the library's {predicate} was not found")

        for symbol in re.findall(r"exceptionCode\s*==\s*([A-Za-z_][A-Za-z0-9_]*)", body):
            if symbol in by_symbol:
                categories[by_symbol[symbol]] = category
            else:
                unmatched.add(symbol)

    # A predicate naming a code the enumeration does not carry means the two have drifted apart.
    # Dropped in silence it would be indistinguishable from an exception no channel filters.
    if unmatched:
        print("exception category predicates naming codes with no entry in the enumeration: "
              + ", ".join(sorted(unmatched)), file=sys.stderr)

    return categories


def parse_feature_masks(
        utils_source: str, libsas_header: str) -> dict[str, list[tuple[int, int]]]:
    """Which enabled-feature bits the library clears for a channel that lacks a category.

    Long poll $A0 is answered on a channel, so a channel that was never given a category must not
    tell its host the machine supports that category. The library masks its own answer; the bits
    it clears are read from there and resolved through the header's macros, so a bit renumbered in
    the library is renumbered here.
    """
    bodies = parse_function_bodies(utils_source)
    body = bodies.get("maskEnabledFeaturesForChannel")
    if body is None:
        raise SystemExit("the library's enabled-features channel mask was not found")

    header = strip_comments(libsas_header)
    defines: dict[str, int] = {}
    # Plain macros, and the enumerated constants a macro may be written in terms of. Both, because
    # the validation style bits are a macro over an enumerator and reading only one kind of
    # definition left two of the four bits out of the mask.
    for name, value in re.findall(
            r"#define\s+([A-Z][A-Z0-9_]*)\s+(0x[0-9A-Fa-f]+|\d+)\s*$", header, re.M):
        defines[name] = int(value, 0)
    for name, value in re.findall(
            r"^\s*([A-Z][A-Z0-9_]*)\s*=\s*(0x[0-9A-Fa-f]+|\d+)\s*,?\s*$", header, re.M):
        defines.setdefault(name, int(value, 0))

    # One of them is written as another macro shifted, which is how the library expresses the
    # reserved value of a two-bit field. Resolved the same way rather than named as a special case.
    for name, base, shift in re.findall(
            r"#define\s+([A-Z][A-Z0-9_]*)\s+\(\s*([A-Z][A-Z0-9_]*)\s*<<\s*(\d+)\s*\)", header):
        if base in defines:
            defines[name] = defines[base] << int(shift)

    masks: dict[str, list[tuple[int, int]]] = {}
    unresolved: set[str] = set()
    gates = list(re.finditer(r"if\s*\(!channelControl\.([A-Za-z_][A-Za-z0-9_]*)\)", body))
    for index, gate in enumerate(gates):
        until = gates[index + 1].start() if index + 1 < len(gates) else len(body)
        for byte, expression in re.findall(
                r"features\[(\d+)\]\s*&=\s*~\(?([^;]+?)\)?\s*;", body[gate.end():until]):
            bits = 0
            for symbol in re.findall(r"[A-Z][A-Z0-9_]*", expression):
                if symbol in defines:
                    bits |= defines[symbol]
                else:
                    unresolved.add(symbol)
            if bits:
                masks.setdefault(gate.group(1), []).append((int(byte), bits))

    if unresolved:
        print("enabled-feature bits the header does not define: " + ", ".join(sorted(unresolved)),
              file=sys.stderr)

    if not masks:
        raise SystemExit("no enabled-feature bits were read out of the channel mask")

    return masks

ANSWER_GATE = re.compile(
    r"if\s*\(([^\n]{0,200}?)\)\s*\n?\s*(?:\{\s*)?return\s*(?:0|1)?\s*;")

#   Conditions every handler carries, which say nothing about whether this command can be asked:
#   a failed shared-memory read, a message for another machine, a bad check sequence, a game number
#   out of range, a mutex that timed out.
ANSWER_GATE_NOISE = ("isError", "egmAddress", "crcCheck", "notFound", "numberOfGames",
                     "internalLockMutex", "rxPacket->length", "rxBuffer->length")


def parse_answer_gates(lp_source: str, dispatch: dict[int, str],
                       bodies: dict[str, str]) -> dict[int, list[str]]:
    """Per command, the conditions under which its handler returns without answering.

    Read verbatim rather than translated, because the point of the list is that somebody can go
    and look at the same line in the library. A handler whose whole body is a call to another one
    - the four tournament meters are all like this - inherits that one's conditions, which is the
    only indirection followed: a second level would start being a guess about control flow.
    """
    gates: dict[int, list[str]] = {}
    for code, handler in dispatch.items():
        body = bodies.get(handler)
        if body is None:
            continue

        delegated = re.fullmatch(
            r"\{\s*(lp[0-9A-Za-z_]+)\s*\([^;]*\)\s*;\s*\}", strip_comments(body).strip())
        if delegated and delegated.group(1) in bodies:
            body = bodies[delegated.group(1)]

        found: list[str] = []
        for match in ANSWER_GATE.finditer(strip_comments(body)):
            condition = " ".join(match.group(1).split())
            if any(noise in condition for noise in ANSWER_GATE_NOISE):
                continue
            if condition not in found:
                found.append(condition)

        if found:
            gates[code] = found

    return gates


def parse_host_message_lengths(uart_source: str) -> dict[int, int]:
    """Reads the receiver's own table of how long each host message is.

    This is the second and better statement of the same rule, and it is the one that decides what
    a machine actually does. The receive path reads the address and the command byte, looks the
    command up here, and then either stops (a total of two), reads exactly this many more bytes
    (a total above two), or reads a length byte and follows it (-1). A message shorter than the
    table says is dropped as incomplete before any handler sees it — which is why a real machine
    answers a two-byte poll of a four-byte command with silence rather than with a refusal.

    It also covers commands the dispatcher answers nowhere, and commands the long poll
    enumeration does not carry at all, so it says more than the handlers can.
    """
    lengths: dict[int, int] = {}
    for match in re.finditer(
            r"long_poll_size\[0x([0-9A-Fa-f]{2})\]\s*=\s*(-?\d+)\s*;", strip_comments(uart_source)):
        lengths[int(match.group(1), 16)] = int(match.group(2))

    if not lengths:
        raise SystemExit("the receiver's long poll size table was not found")

    return lengths


def reconcile_check_sequences(
        lengths: dict[int, int], from_handlers: dict[int, bool]) -> dict[int, bool]:
    """Settles the check-sequence rule from both statements, and reports any disagreement.

    Two readings of two different files: what each handler checks, and what the receiver frames.
    They are combined rather than one being preferred, because a disagreement between them would
    be a fact about the library worth knowing and averaging them would hide it. There are none
    today, over every command where both speak.
    """
    settled: dict[int, bool] = {}
    conflicts: list[str] = []

    for code, length in sorted(lengths.items()):
        # A variable-length message is address, command, a length byte, its data and a check
        # sequence, so it is always longer than two bytes and always carries one.
        framed = length != 2

        if code in from_handlers and from_handlers[code] != framed:
            conflicts.append(
                f"${code:02X}: the receiver frames {length} byte(s) and the handler "
                f"{'checks' if from_handlers[code] else 'does not check'} a sequence")

        settled[code] = framed

    # A command the receiver's table does not mention is framed by a length byte, so it carries a
    # check sequence too; the handler reading is what says so, and it is kept.
    for code, required in from_handlers.items():
        settled.setdefault(code, required)

    if conflicts:
        print("the library's two statements of the check sequence rule disagree:\n  "
              + "\n  ".join(conflicts), file=sys.stderr)

    return settled


def strip_comments(source: str) -> str:
    """Blanks out comments, keeping the line structure so nothing shifts.

    The dispatcher has a whole commented-out switch in it. Scanned as written, its case labels read
    as live ones, and the only thing keeping the answer right today is that its breaks are
    commented out too and the scan matches those as well. That is a coincidence, not a rule.
    """
    blanked = re.sub(BLOCK_COMMENT, lambda m: re.sub(NOT_NEWLINE, " ", m.group(0)), source, flags=re.S)
    return re.sub(LINE_COMMENT, "", blanked)


def spaced(identifier: str) -> str:
    """Turns SendGamingMachineIdAndInformation into 'Send gaming machine id and information'."""
    words = re.sub(r"(?<!^)(?=[A-Z])", " ", identifier).replace("_", " ").split()
    if not words:
        return identifier
    return " ".join([words[0].capitalize()] + [w.lower() for w in words[1:]])


def escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"')


def xml_escape(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def unique_names(entries: list[Entry]) -> list[Entry]:
    """Drops later duplicates of the same value, keeping the first spelling."""
    seen: set[int] = set()
    kept: list[Entry] = []
    for entry in entries:
        if entry.value in seen:
            continue
        seen.add(entry.value)
        kept.append(entry)
    return kept


def header(sources: str, usings: str = "") -> str:
    return HEADER.format(sources=sources, usings=usings)



def csharp_category(name: str) -> str:
    """Turns the library's generalControl into GeneralControl."""
    return name[:1].upper() + name[1:]


def emit_categories(categories: list[str], sources: str) -> str:
    """The seven categories a channel can own, as the library's own structure names them."""
    lines = [header(sources),
             "/// <summary>",
             "/// One of the categories of SAS traffic a channel can be given ownership of.",
             "/// </summary>",
             "/// <remarks>",
             "/// Read from the gaming machine library's channel-control structure, whose one-bit",
             "/// fields are the only place the library states what the independences are. The",
             "/// platform above it lists the same seven in the same order, as seven two-bit fields",
             "/// each holding one channel number - so a category cannot be on two channels at once,",
             "/// and disjointness is a property of the machine rather than a rule a host has to",
             "/// police.",
             "/// </remarks>",
             "public enum SasCategory", "{"]
    for index, name in enumerate(categories):
        lines.append(f"    /// <summary>{spaced(csharp_category(name))}.</summary>")
        lines.append(f"    {csharp_category(name)} = {index},")
        lines.append("")
    if lines[-1] == "":
        lines.pop()
    lines.append("}")
    return "\n".join(lines) + "\n"


def emit_enum(
    csharp_name: str,
    underlying: str,
    entries: list[Entry],
    sources: str,
    doc: str,
) -> str:
    lines = [header(sources), f"/// <summary>{doc}</summary>",
             f"public enum {csharp_name} : {underlying}", "{"]
    for entry in entries:
        if entry.summary:
            lines.append(f"    /// <summary>{xml_escape(entry.summary)}</summary>")
        lines.append(f"    {entry.name} = 0x{entry.value:02X},")
        lines.append("")
    if lines[-1] == "":
        lines.pop()
    lines.append("}")
    return "\n".join(lines) + "\n"


def emit_catalogue(
    long_polls: list[Entry],
    handlers: dict[int, str],
    handlers_full: dict[int, str],
    check_sequences: dict[int, bool],
    host_lengths: dict[int, int],
    exceptions: list[Entry],
    meters: list[Entry],
    meter_reads: dict[int, tuple[list[int], bool]],
    multigame_meters: list[int],
    command_categories: dict[int, str],
    exception_categories: dict[int, str],
    feature_masks: dict[str, list[tuple[int, int]]],
    answer_gates: dict[int, list[str]],
    sources: str,
) -> str:
    lines = [header(sources, "\nusing System.Collections.Frozen;\n"),
             "/// <summary>",
             "/// Every long poll, exception and meter the gaming machine library knows about,",
             "/// with the name it uses for each.",
             "/// </summary>",
             "public static class SasCatalogue", "{"]

    lines.append("    /// <summary>Long poll commands, by code.</summary>")
    lines.append("    public static FrozenDictionary<byte, SasLongPollInfo> LongPolls { get; } =")
    lines.append("        new Dictionary<byte, SasLongPollInfo>")
    lines.append("        {")
    for entry in long_polls:
        handler = handlers.get(entry.value)
        description = spaced(handler) if handler else spaced(entry.name.removeprefix("LP_").title())
        # The handler is carried as well as spelled out, because whether the dispatcher sends this
        # command anywhere decides whether a layout for it can be read out of the library at all.
        named = f'"{escape(handlers_full[entry.value])}"' if entry.value in handlers_full else "null"
        checked = "null"
        if entry.value in check_sequences:
            checked = "true" if check_sequences[entry.value] else "false"
        framed = "null"
        if entry.value in host_lengths:
            framed = str(host_lengths[entry.value])
        lines.append(
            f'            [0x{entry.value:02X}] = new(0x{entry.value:02X}, "{entry.name}", '
            f'"{escape(description)}", {named}, {checked}, {framed}),')
    lines.append("        }.ToFrozenDictionary();")
    lines.append("")

    lines.append("    /// <summary>")
    lines.append("    /// How many bytes the gaming machine library's receiver frames a host")
    lines.append("    /// message at, command by command, or -1 where it follows a length byte.")
    lines.append("    /// </summary>")
    lines.append("    /// <remarks>")
    lines.append("    /// Read from the receive path rather than from a handler, and it says more")
    lines.append("    /// than the handlers can: it carries commands the dispatcher answers")
    lines.append("    /// nowhere, and commands the long poll enumeration does not name at all. A")
    lines.append("    /// message shorter than this is dropped as incomplete before a handler sees")
    lines.append("    /// it, which is why such a poll is met with silence and not a refusal.")
    lines.append("    /// </remarks>")
    lines.append("    public static FrozenDictionary<byte, int> HostMessageLengths { get; } =")
    lines.append("        new Dictionary<byte, int>")
    lines.append("        {")
    for code in sorted(host_lengths):
        lines.append(f'            [0x{code:02X}] = {host_lengths[code]},')
    lines.append("        }.ToFrozenDictionary();")
    lines.append("")

    lines.append("    /// <summary>")
    lines.append("    /// The conditions under which a command's handler returns without")
    lines.append("    /// answering, in the library's own words.")
    lines.append("    /// </summary>")
    lines.append("    /// <remarks>")
    lines.append("    /// Copied verbatim rather than translated, so that a claim made from one")
    lines.append("    /// can be checked against the same line in the library. This is what lets")
    lines.append("    /// a command with no layout say why it has none — a feature bit the")
    lines.append("    /// machine must advertise, a channel category it must own, a thing that")
    lines.append("    /// has to be configured first — instead of being counted as work nobody")
    lines.append("    /// has got to yet. The conditions every handler carries are left out: a")
    lines.append("    /// failed memory read, a message for another machine, a bad check")
    lines.append("    /// sequence, a game number out of range.")
    lines.append("    /// </remarks>")
    lines.append("    public static FrozenDictionary<byte, IReadOnlyList<string>> AnswerGates "
                 "{ get; } =")
    lines.append("        new Dictionary<byte, IReadOnlyList<string>>")
    lines.append("        {")
    for code in sorted(answer_gates):
        rendered = ", ".join(f'"{escape(gate)}"' for gate in answer_gates[code])
        lines.append(f'            [0x{code:02X}] = new[] {{ {rendered} }},')
    lines.append("        }.ToFrozenDictionary();")
    lines.append("")
    lines.append("    /// <summary>Exception codes, by code.</summary>")
    lines.append("    public static FrozenDictionary<byte, SasExceptionInfo> Exceptions { get; } =")
    lines.append("        new Dictionary<byte, SasExceptionInfo>")
    lines.append("        {")
    for entry in exceptions:
        description = entry.summary or spaced(entry.name)
        lines.append(
            f'            [0x{entry.value:02X}] = new(0x{entry.value:02X}, "{entry.name}", '
            f'"{escape(description)}"),')
    lines.append("        }.ToFrozenDictionary();")
    lines.append("")

    lines.append("    /// <summary>Meter codes, by code.</summary>")
    lines.append("    public static FrozenDictionary<ushort, SasMeterInfo> Meters { get; } =")
    lines.append("        new Dictionary<ushort, SasMeterInfo>")
    lines.append("        {")
    for entry in meters:
        description = entry.summary or spaced(entry.name)
        lines.append(
            f'            [0x{entry.value:04X}] = new(0x{entry.value:04X}, "{entry.name}", '
            f'"{escape(description)}"),')
    lines.append("        }.ToFrozenDictionary();")
    lines.append("")
    lines.append("    /// <summary>")
    lines.append("    /// Which meters each long poll reports, in the order its reply writes them,")
    lines.append("    /// and whether it reads them through the library's shared single-meter helper.")
    lines.append("    /// </summary>")
    lines.append("    /// <remarks>")
    lines.append("    /// Read from the handler the dispatcher sends the command to. The distinction")
    lines.append("    /// the second half draws is not cosmetic: the shared helper divides a meter")
    lines.append("    /// that is not one of the multigame meters by the accounting denomination,")
    lines.append("    /// under two of the machine's five meter modes, and every other handler")
    lines.append("    /// writes the meter as it stands. So two commands reporting one meter can")
    lines.append("    /// answer two different numbers, and which of them a test should be reading")
    lines.append("    /// is decided here rather than guessed at.")
    lines.append("    /// </remarks>")
    lines.append("    public static FrozenDictionary<byte, SasMeterReadInfo> MeterReads { get; } =")
    lines.append("        new Dictionary<byte, SasMeterReadInfo>")
    lines.append("        {")
    for code in sorted(meter_reads):
        codes, shared = meter_reads[code]
        written = ", ".join(f"0x{value:04X}" for value in codes)
        lines.append(
            f'            [0x{code:02X}] = new(0x{code:02X}, [{written}], '
            f'{"true" if shared else "false"}),')
    lines.append("        }.ToFrozenDictionary();")
    lines.append("")
    lines.append("    /// <summary>")
    lines.append("    /// The meters the library calls multigame, read from the predicate that")
    lines.append("    /// decides it. The shared single-meter helper leaves these alone and divides")
    lines.append("    /// every other meter by the accounting denomination.")
    lines.append("    /// </summary>")
    lines.append("    public static FrozenSet<ushort> MultigameMeters { get; } =")
    lines.append("        new ushort[]")
    lines.append("        {")
    for value in multigame_meters:
        lines.append(f'            0x{value:04X},')
    lines.append("        }.ToFrozenSet();")
    lines.append("")
    lines.append("    /// <summary>")
    lines.append("    /// Which channel category owns each long poll, where the library gates one.")
    lines.append("    /// </summary>")
    lines.append("    /// <remarks>")
    lines.append("    /// A channel that was not given a category behaves as though the category did")
    lines.append("    /// not exist, and the library implements that by returning without sending")
    lines.append("    /// anything - so a host on the wrong channel is met with silence rather than")
    lines.append("    /// with a refusal. A command absent from this table is answered on any")
    lines.append("    /// channel, which is a fact about the library and not a gap here.")
    lines.append("    /// </remarks>")
    lines.append("    public static FrozenDictionary<byte, SasCategory> CommandCategories { get; } =")
    lines.append("        new Dictionary<byte, SasCategory>")
    lines.append("        {")
    for code in sorted(command_categories):
        lines.append(
            f'            [0x{code:02X}] = SasCategory.{csharp_category(command_categories[code])},')
    lines.append("        }.ToFrozenDictionary();")
    lines.append("")
    lines.append("    /// <summary>")
    lines.append("    /// Which channel category owns each exception, where the library filters one.")
    lines.append("    /// </summary>")
    lines.append("    /// <remarks>")
    lines.append("    /// The library keeps one exception buffer per channel and skips a channel that")
    lines.append("    /// does not own the exception's category, so this decides which host hears")
    lines.append("    /// what. An exception in no category reaches every open channel.")
    lines.append("    /// </remarks>")
    lines.append("    public static FrozenDictionary<byte, SasCategory> ExceptionCategories { get; } =")
    lines.append("        new Dictionary<byte, SasCategory>")
    lines.append("        {")
    for code in sorted(exception_categories):
        lines.append(
            f'            [0x{code:02X}] = SasCategory.{csharp_category(exception_categories[code])},')
    lines.append("        }.ToFrozenDictionary();")
    lines.append("")
    lines.append("    /// <summary>")
    lines.append("    /// Which enabled-feature bits the library clears when answering on a channel")
    lines.append("    /// that does not own the category, by feature byte.")
    lines.append("    /// </summary>")
    lines.append("    /// <remarks>")
    lines.append("    /// The features describe the machine and are configured once, but the poll that")
    lines.append("    /// reports them is answered on a channel - so a channel with no validation must")
    lines.append("    /// not tell its host the machine redeems tickets.")
    lines.append("    /// </remarks>")
    lines.append("    public static FrozenDictionary<SasCategory, IReadOnlyList<SasFeatureMask>>")
    lines.append("        ChannelFeatureMasks { get; } =")
    lines.append("        new Dictionary<SasCategory, IReadOnlyList<SasFeatureMask>>")
    lines.append("        {")
    for category in sorted(feature_masks):
        written = ", ".join(
            f"new({index}, 0x{bits:02X})" for index, bits in feature_masks[category])
        lines.append(
            f'            [SasCategory.{csharp_category(category)}] = [{written}],')
    lines.append("        }.ToFrozenDictionary();")
    lines.append("")
    lines.append("    /// <summary>How many of each the catalogue holds, for a report header.</summary>")
    lines.append("    public static (int LongPolls, int Exceptions, int Meters) Counts =>")
    lines.append("        (LongPolls.Count, Exceptions.Count, Meters.Count);")
    lines.append("}")
    return "\n".join(lines) + "\n"


def emit_info_types(sources: str) -> str:
    return header(sources) + """
/// <summary>One long poll command, as the gaming machine library names it.</summary>
/// <param name="Code">The command byte.</param>
/// <param name="Symbol">The library's own identifier for it.</param>
/// <param name="Description">What it does, taken from the library's handler name.</param>
/// <param name="Handler">
/// The handler the library's own dispatcher sends this command to, or null when the dispatcher
/// does not list it at all. A command with no handler is one whose layout cannot be read out of
/// the library, however well another description of the protocol may name it.
/// </param>
/// <param name="RequiresCheckSequence">
/// True when the library's handler for this command refuses a host message that does not end in a
/// frame check sequence, so a two-byte poll of it is rejected however well formed it looks. Null
/// when neither the receiver's own framing table nor a handler says.
/// </param>
/// <param name="HostMessageLength">
/// How many bytes the library's receiver frames the host's message at, including the address, the
/// command and any check sequence; -1 where it follows a length byte in the message instead, and
/// null where the table does not carry this command. A shorter message is dropped as incomplete
/// before any handler sees it.
/// </param>
public sealed record SasLongPollInfo(
    byte Code, string Symbol, string Description, string? Handler = null,
    bool? RequiresCheckSequence = null, int? HostMessageLength = null)
{
    public override string ToString() => $"${Code:X2} {Description}";
}

/// <summary>One exception code.</summary>
/// <param name="Code">The code a general poll returns.</param>
/// <param name="Symbol">The library's own identifier for it.</param>
/// <param name="Description">What it means, from the library's own documentation.</param>
public sealed record SasExceptionInfo(byte Code, string Symbol, string Description)
{
    public override string ToString() => $"${Code:X2} {Description}";
}

/// <summary>Which meters one long poll reports, and how the library reads them.</summary>
/// <param name="Command">The command byte.</param>
/// <param name="Meters">
/// The meters its reply carries, in the order the handler writes them. A command whose reply
/// carries one number computed from several meters lists all of them.
/// </param>
/// <param name="ThroughSharedHandler">
/// True when the library answers this command through its shared single-meter helper, which
/// divides a meter that is not multigame by the accounting denomination under two of the five
/// meter modes. False when the handler writes the meter as it stands.
/// </param>
public sealed record SasMeterReadInfo(
    byte Command, IReadOnlyList<ushort> Meters, bool ThroughSharedHandler)
{
    public override string ToString() =>
        $"${Command:X2} {Meters.Count} meter(s)" + (ThroughSharedHandler ? ", scaled" : string.Empty);
}

/// <summary>One run of enabled-feature bits a channel without a category must not report.</summary>
/// <param name="Byte">Which of the three feature bytes, zero-based.</param>
/// <param name="Mask">The bits the library clears in it.</param>
public readonly record struct SasFeatureMask(int Byte, byte Mask)
{
    public override string ToString() => $"features[{Byte}] &= ~0x{Mask:X2}";
}

/// <summary>One meter.</summary>
/// <param name="Code">The meter code.</param>
/// <param name="Symbol">The library's own identifier for it.</param>
/// <param name="Description">What it counts, from the library's own documentation.</param>
public sealed record SasMeterInfo(ushort Code, string Symbol, string Description)
{
    public override string ToString() => $"${Code:X4} {Description}";
}
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--libsas", default=r"C:\Progetti\libsas",
                        help="root of the gaming machine library checkout")
    parser.add_argument("--check", action="store_true",
                        help="do not write; exit non-zero if the committed output is stale")
    args = parser.parse_args()

    root = Path(args.libsas)
    libsas_h = root / "include" / "libsas.h"
    lp_h = root / "include" / "lp.h"
    threads_cpp = root / "src" / "libsas_threads.cpp"
    lp_cpp = root / "src" / "lp.cpp"
    uart_cpp = root / "src" / "libsas_uart.cpp"
    utils_cpp = root / "src" / "libsas_utils.cpp"
    wrapper_h = root / "include" / "libsas_wrapper.h"
    if (not libsas_h.exists() or not lp_h.exists() or not threads_cpp.exists()
            or not lp_cpp.exists() or not uart_cpp.exists() or not utils_cpp.exists()
            or not wrapper_h.exists()):
        print(f"headers not found under {root}", file=sys.stderr)
        return 2

    source = read(libsas_h)
    sources = ("include/libsas.h, include/lp.h, include/libsas_wrapper.h, "
               "src/libsas_threads.cpp, src/lp.cpp, src/libsas_uart.cpp, src/libsas_utils.cpp")

    long_polls = unique_names(parse_enum(source, "SasLongPollCode"))
    exceptions = unique_names(parse_enum(source, "SasExceptionCode"))
    meters = unique_names(parse_enum(source, "SasMeterCode"))
    ticket_status = unique_names(parse_enum(source, "LP_TICKET_STATUS"))
    transfer_codes = unique_names(parse_enum(source, "_LP_TICKET_TRANSFER_CODE"))
    machine_status = unique_names(parse_enum(source, "_LP_GAMING_MACHINE_STATUS_CODES"))
    handlers = parse_long_poll_handlers(read(lp_h))
    handlers_full = parse_dispatch(read(threads_cpp), long_polls)
    from_handlers = parse_check_sequences(read(lp_cpp), handlers_full)
    host_lengths = parse_host_message_lengths(read(uart_cpp))
    check_sequences = reconcile_check_sequences(host_lengths, from_handlers)
    meter_reads = parse_meter_reads(read(lp_cpp), handlers_full, meters)
    multigame_meters = parse_multigame_meters(read(utils_cpp), meters)
    categories = parse_channel_categories(read(wrapper_h))
    command_categories = parse_command_categories(read(lp_cpp), handlers_full, long_polls)
    exception_categories = parse_exception_categories(read(utils_cpp), exceptions)
    feature_masks = parse_feature_masks(read(utils_cpp), source)
    answer_gates = parse_answer_gates(
        read(lp_cpp), handlers_full, parse_function_bodies(read(lp_cpp)))

    files = {
        "SasLongPollCode.g.cs": emit_enum(
            "SasLongPollCode", "byte", long_polls, sources,
            "Every long poll command the gaming machine library dispatches."),
        "SasExceptionCode.g.cs": emit_enum(
            "SasExceptionCode", "byte", exceptions, sources,
            "Every exception a gaming machine can report in answer to a general poll."),
        "SasMeterCode.g.cs": emit_enum(
            "SasMeterCode", "ushort", meters, sources,
            "Every meter the gaming machine library can report."),
        "SasTicketStatus.g.cs": emit_enum(
            "SasTicketStatus", "byte", ticket_status, sources,
            "Whether the gaming machine is holding a ticket in its acceptor."),
        "SasTicketTransferCode.g.cs": emit_enum(
            "SasTicketTransferCode", "byte", transfer_codes, sources,
            "What a host tells a gaming machine to do with the ticket it is holding."),
        "SasTicketMachineStatus.g.cs": emit_enum(
            "SasTicketMachineStatus", "byte", machine_status, sources,
            "What a gaming machine reports it did with a ticket."),
        "SasCategory.g.cs": emit_categories(categories, sources),
        "CatalogueInfo.g.cs": emit_info_types(sources),
        "Catalogue.g.cs": emit_catalogue(
            long_polls, handlers, handlers_full, check_sequences, host_lengths,
            exceptions, meters, meter_reads, multigame_meters, command_categories,
            exception_categories, feature_masks, answer_gates, sources),
    }

    stale = []
    for name, text in files.items():
        target = OUT_DIR / name
        current = read(target) if target.exists() else None
        if current == text:
            continue
        stale.append(name)
        if not args.check:
            target.parent.mkdir(parents=True, exist_ok=True)
            io.open(target, "w", encoding="utf-8", newline="\n").write(text)

    if args.check:
        if stale:
            print("stale generated files: " + ", ".join(sorted(stale)), file=sys.stderr)
            return 1
        print("generated catalogue is up to date")
        return 0

    print(f"{len(long_polls)} long polls, {len(exceptions)} exceptions, {len(meters)} meters, "
          f"{len(transfer_codes)} ticket transfer codes, {len(machine_status)} machine "
          f"statuses, {len(categories)} channel categories owning "
          f"{len(command_categories)} command(s) and {len(exception_categories)} exception(s) "
          f"-> {OUT_DIR.relative_to(REPO)}")
    if stale:
        print("updated: " + ", ".join(sorted(stale)))
    else:
        print("no changes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
